# -*- coding: utf-8 -*-
"""Paper table: leave-one-day-out validation per held-out day and pooled (same cycles as the figures).

Usage: python paper_table_validation.py  -> Paper/JAerosolSci/tables/tab_validation.tex
"""
import os

import pandas as pd

from paper_fig_n_validation import DAYS, load
from paper_style import HERE

OUT = os.path.join(HERE, os.pardir, "Paper", "JAerosolSci", "tables", "tab_validation.tex")


def stats(d):
    r, q = d.nd_cm3 / d.cpc, d.qw_gkg / d.qw_ref_td_gkg
    return dict(
        n=f"{len(d)}",
        hyg=f"{d.qw_ref_td_gkg.min():.1f}--{d.qw_ref_td_gkg.max():.1f}",
        cpc=f"{d.cpc.min():.0f}--{d.cpc.max():.0f}",
        q=f"{q.median():.3f} ({q.quantile(.25):.3f}--{q.quantile(.75):.3f})",
        qci=f"{((d.qw_ref_td_gkg >= d.qw_lo) & (d.qw_ref_td_gkg <= d.qw_hi)).mean()*100:.0f}",
        r=f"{r.median():.3f} ({r.quantile(.25):.3f}--{r.quantile(.75):.3f})",
        corr=f"{d.nd_cm3.corr(d.cpc):.3f}",
        nci=f"{((d.cpc >= d.nd_cm3_lo) & (d.cpc <= d.nd_cm3_hi)).mean()*100:.0f}")


def main():
    rows = []
    for lab, f, a, b, _, _ in DAYS:
        d = load(f, a, b)
        rows.append((lab, stats(d)))
    rows.append(("All", stats(pd.concat([load(f, a, b) for _, f, a, b, _, _ in DAYS]))))
    lines = [r"\begin{tabular}{lrlllllll}", r"\toprule",
             r" & & & & \multicolumn{2}{l}{Water vapor mixing ratio} & "
             r"\multicolumn{3}{l}{Particle number concentration} \\",
             r"\cmidrule(lr){5-6}\cmidrule(l){7-9}",
             r"Held-out day & Cycles & $q_{w,\mathrm{hyg}}$ & $N_\mathrm{CPC}$ & $q_w/q_{w,\mathrm{hyg}}$ & "
             r"In 90\,\% CI & $N/N_\mathrm{CPC}$ & $r$ & In 90\,\% CI \\",
             r" & & (g\,kg$^{-1}$) & (cm$^{-3}$) & median (IQR) & (\%) & median (IQR) & & (\%) \\", r"\midrule"]
    for lab, s in rows:
        if lab == "All":
            lines.append(r"\midrule")
        lines.append(f"{lab} & {s['n']} & {s['hyg']} & {s['cpc']} & {s['q']} & {s['qci']} & {s['r']} & "
                     f"{s['corr']} & {s['nci']} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("% generated by Python/paper_table_validation.py\n" + "\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
