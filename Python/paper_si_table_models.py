# -*- coding: utf-8 -*-
"""SI table: validation of the individual models on each day (same cycles as the paper figures).

Models: leave-one-day-out (the paper's estimates: each day by the model calibrated without it),
calibrated on 31 Oct-1 Nov only (time split; 2 Nov held out), and calibrated on all days.

Usage: python paper_si_table_models.py  -> Paper/JAerosolSci/tables/tab_s_models.tex
"""
import os

import pandas as pd

from paper_fig_n_validation import DAYS, load
from paper_style import HERE

OUT = os.path.join(HERE, os.pardir, "Paper", "JAerosolSci", "tables", "tab_s_models.tex")
MODELS = [("Leave-one-day-out", None),
          ("Trained on 31 Oct--1 Nov", "reanalysis_nopcorr-cal1031-1101.csv"),
          ("Trained on all days", "reanalysis_nopcorr-all.csv")]
HELD_OUT_CAL = {"2 Nov"}  # days not used by the 31 Oct-1 Nov model


def row(d):
    r, q = d.nd_cm3 / d.cpc, d.qw_gkg / d.qw_ref_td_gkg
    return (f"{len(d)} & {r.median():.3f} ({r.quantile(.25):.3f}--{r.quantile(.75):.3f}) & "
            f"{d.nd_cm3.corr(d.cpc):.3f} & {((d.cpc >= d.nd_cm3_lo) & (d.cpc <= d.nd_cm3_hi)).mean()*100:.0f} & "
            f"{q.median():.3f} ({q.quantile(.25):.3f}--{q.quantile(.75):.3f})")


def main():
    lines = [r"\begin{tabular}{llrllrl}", r"\toprule",
             r"Estimator & Day & Cycles & $N/N_\mathrm{CPC}$ & $r$ & In 90\,\% CI & $q_w/q_{w,\mathrm{hyg}}$ \\",
             r" & & & median (IQR) & & (\%) & median (IQR) \\", r"\midrule"]
    for k, (name, fname) in enumerate(MODELS):
        if k:
            lines.append(r"\midrule")
        days = []
        for lab, f, a, b, _, _ in DAYS:
            d = load(fname or f, a, b)
            days.append(d)
            in_sample = fname is not None and (k == len(MODELS) - 1 or lab not in HELD_OUT_CAL)
            mark = "$^{a}$" if in_sample else ""
            lines.append(f"{name if not days[1:] else ''} & {lab}{mark} & {row(d)} \\\\")
        lines.append(f" & All & {row(pd.concat(days))} \\\\")
    lines += [r"\bottomrule",
              r"\multicolumn{7}{l}{\footnotesize $^{a}$ Day used in training.}\\",
              r"\end{tabular}"]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write("% Generated by Python/paper_si_table_models.py\n" + "\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
