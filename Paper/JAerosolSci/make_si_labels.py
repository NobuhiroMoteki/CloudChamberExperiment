"""Write si_labels.tex: the labels of the supplement (S1, Fig. S3, ...) declared for main.tex.

main.tex refers to the supplement as \\ref{S-<label>}. The xr package would need build/supplement.aux
at build time, which Editorial Manager does not accept, so that every reference would become "??" in
the typeset paper. The labels are therefore declared in si_labels.tex, which is submitted with
main.tex. Re-run after any change of the supplement's numbering:
  latexmk -lualatex -outdir=build supplement.tex && python make_si_labels.py && latexmk -lualatex -outdir=build main.tex

Usage: python make_si_labels.py  (from Paper/JAerosolSci) -> si_labels.tex
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
AUX = os.path.join(HERE, "build", "supplement.aux")
OUT = os.path.join(HERE, "si_labels.tex")


def main():
    labels = re.findall(r"\\newlabel\{((?:sec|fig|tab|eq):s[-_][^}]*)\}\{\{([^}]*)\}", open(AUX).read())
    lines = ["% Labels of the supplement, generated by make_si_labels.py from build/supplement.aux.",
             "% Do not edit by hand; re-run the script when the numbering of the supplement changes."]
    lines += [f"\\newlabel{{S-{name}}}{{{{{number}}}{{1}}{{}}{{}}{{}}}}" for name, number in labels]
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{len(labels)} labels -> {OUT}")


if __name__ == "__main__":
    main()
